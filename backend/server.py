@app.route("/api/agricultural-search", methods=["POST"])
def agricultural_search_endpoint():
    """
    Search agricultural intelligence (symptoms, prevention, IPM,
    official extension advisories) through SerpApi.
    Accepts JSON or Form-data: { crop, disease, query, category }
    """
    data = request.get_json(silent=True) or request.form

    crop = data.get("crop", "").strip()
    disease = data.get("disease", "").strip()
    query = data.get("query", "").strip()
    category = data.get("category", "all").strip()

    try:
        search_result = search_agricultural_intelligence(
            crop_name=crop,
            disease_name=disease,
            query=query,
            category=category
        )
        return jsonify(search_result)
    except Exception as exc:
        app.logger.exception("Agricultural search endpoint error: %s", exc)
        return jsonify({
            "success": False,
            "sources": [],
            "message": f"Search failed: {str(exc)}"
        }), 500


