# ==========================================
@app.route("/api/diagnose", methods=["POST"])
def diagnose():
    """
    Accepts multipart image upload, preprocesses, performs YOLO inference,
    evaluates confidence and crop uncertainty, and returns top-3 predictions
    along with verified agricultural guidance and optional references.
    """
    if "image" not in request.files:
        return jsonify({"success": False, "error": "No image file provided in upload."}), 400

    uploaded_file = request.files["image"]
    if not uploaded_file or uploaded_file.filename == "":
        return jsonify({"success": False, "error": "No image file selected."}), 400

    # Optional crop hint provided by user (e.g. 'Paddy', 'Cotton', 'Auto-detect')
    crop_hint = request.form.get("crop_hint", "").strip()

    # Validate file extension
    filename = uploaded_file.filename.lower()
    allowed_exts = {".jpg", ".jpeg", ".png", ".webp"}
    file_ext = Path(filename).suffix
    if file_ext not in allowed_exts:
        return jsonify({
            "success": False,
            "error": f"Unsupported file extension '{file_ext}'. Allowed formats: JPG, JPEG, PNG, WebP."
        }), 400

    # Read bytes safely into PIL Image
    try:
        image_bytes = uploaded_file.read()
        if len(image_bytes) == 0:
            return jsonify({"success": False, "error": "Uploaded image file is empty."}), 400

        image = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    except Exception as exc:
        app.logger.warning("Failed to parse uploaded image: %s", exc)
        return jsonify({"success": False, "error": "Corrupted or invalid image file."}), 400

    width, height = image.size
    image_warnings = []
    if width < 224 or height < 224:
        image_warnings.append(
            f"Image resolution ({width}x{height}) is lower than the recommended 224x224. "
            "For highest diagnostic precision, upload a clear, high-resolution leaf photo."
        )

    # Check for crop hint status: vision-trained vs expanded knowledge
    is_hint_expanded = False
    is_hint_unsupported = False
    hint_matched_name = None

    if crop_hint and crop_hint.lower() not in {"auto", "auto-detect", ""}:
        for exp_crop in EXPANDED_KNOWLEDGE_CROPS:
            if exp_crop.lower() in crop_hint.lower():
                is_hint_expanded = True
                hint_matched_name = exp_crop
                break
        if not is_hint_expanded and not is_vision_model_supported(crop_hint):
            is_hint_unsupported = True
            hint_matched_name = crop_hint

    # Perform YOLO Inference with GPU memory safeguards & CPU fallback
    global DEVICE
    inference_device = DEVICE
    try:
        with torch.no_grad():
            results = model.predict(source=image, device=inference_device, verbose=False)
    except torch.cuda.OutOfMemoryError:
        app.logger.warning("CUDA Out of Memory encountered! Switching to CPU fallback.")
        torch.cuda.empty_cache()
        inference_device = "cpu"
        with torch.no_grad():
            results = model.predict(source=image, device="cpu", verbose=False)
    except Exception as exc:
        app.logger.exception("Model prediction failed: %s", exc)
        # Attempt fallback to CPU
        try:
            with torch.no_grad():
                results = model.predict(source=image, device="cpu", verbose=False)
        except Exception as cpu_exc:
            return jsonify({
                "success": False,
                "error": f"Inference engine failed to analyze image: {str(cpu_exc)}"
            }), 500

    result = results[0]
    probabilities = result.probs
    top1_index = int(probabilities.top1)
    top1_confidence = float(probabilities.top1conf)
    top1_class_name = str(model.names[top1_index])

    # Extract Top-3 predictions
    top_predictions = []
    top_indices = probabilities.top5[:3] if hasattr(probabilities, "top5") else [top1_index]
    for idx in top_indices:
        idx = int(idx)
        cls_name = str(model.names[idx])
        conf_val = float(probabilities.data[idx])
        c_crop = get_crop_name(cls_name)
        c_cond = get_condition_name(cls_name)
        top_predictions.append({
            "class_name": cls_name,
            "crop": c_crop,
            "crop_display": clean_display_name(c_crop),
            "condition": c_cond,
            "condition_display": clean_display_name(c_cond),
            "confidence": round(conf_val * 100, 1),
            "confidence_level": confidence_level(conf_val)
        })

    primary_crop = get_crop_name(top1_class_name)
    primary_condition = get_condition_name(top1_class_name)
    crop_display = clean_display_name(primary_crop)
    condition_display = clean_display_name(primary_condition)
    confidence_pct = round(top1_confidence * 100, 1)
    level = confidence_level(top1_confidence)

    # ==========================================
    # UNCERTAINTY & REJECTION MECHANISM
    # ==========================================
    is_uncertain = False
    rejection_reason = None
    rejection_message = None

    if is_hint_expanded:
        is_uncertain = True
        rejection_reason = f"Crop '{hint_matched_name}' is in Knowledge Base & Search; vision model v5 training is queued."
        rejection_message = (
            f"Notice: '{hint_matched_name}' is available in AgriIntel's Knowledge Base & Live Agricultural Search ({len(DISEASE_KNOWLEDGE)} conditions across {len(ALL_KNOWLEDGE_CROPS)} crops). "
            f"However, image-based neural detection for {hint_matched_name} is currently queued in the v5 training pipeline. "
            f"The v4.2 vision model was trained on 16 crops (Apple, Blueberry, Cherry, Corn, Grape, Orange, Paddy, Peach, Bell Pepper, Potato, Raspberry, Soybean, Squash, Strawberry, Tomato, Wheat)."
        )
    elif is_hint_unsupported:
        is_uncertain = True
        rejection_reason = f"Crop '{hint_matched_name}' is not supported by the model."
        rejection_message = (
            f"Notice: '{hint_matched_name}' is outside AgriIntel's current 16 vision-supported crops. "
            f"Please consult a local agricultural officer or KVK for {hint_matched_name} diagnosis."
        )
    elif top1_confidence < 0.45:
        is_uncertain = True
        rejection_reason = "Low model confidence (< 45%)."
        rejection_message = REJECTION_MESSAGE_UNSUPPORTED
    elif len(top_predictions) >= 2:
        top1_crop = top_predictions[0]["crop"]
        top2_crop = top_predictions[1]["crop"]
        top1_score = top_predictions[0]["confidence"]
        top2_score = top_predictions[1]["confidence"]
        # Disparate crops with margin < 15% and neither > 65%
        if top1_crop != top2_crop and (top1_score - top2_score) < 15.0 and top1_score < 65.0:
            is_uncertain = True
            rejection_reason = "Ambiguous prediction between multiple different crops."
            rejection_message = REJECTION_MESSAGE_UNSUPPORTED

    # ==========================================
    # RETRIEVE VERIFIED AGRICULTURAL GUIDANCE
    # ==========================================
    disease_info = get_disease_info(top1_class_name)
    if disease_info is None:
        # Fallback when exact guidance is missing
        is_healthy = primary_condition.lower() in {"healthy", "normal"}
        disease_info = {
            "crop": primary_crop,
            "crop_display": crop_display,
            "condition": condition_display,
            "pathogen": "Not specified",
            "is_healthy": is_healthy,
            "severity": "None" if is_healthy else "Unknown",
            "description": (
                f"The model classified this plant as {condition_display} on {crop_display}. "
                "Guidance not available for this condition yet."
            ),
            "symptoms": [
                "Guidance not available for this condition yet in the verified knowledge base.",
                "Compare the plant against official agricultural extension literature."
            ],
            "recommended_next_steps": [
                "Inspect multiple plants across the plot to establish symptom consistency.",
                "Consult a qualified agricultural extension officer or local KVK before taking action."
            ],
            "preventive_practices": [
                "Follow standard sanitation and balanced crop nutrition practices."
            ]
        }

    # ==========================================
    # OPTIONAL INTEGRATED AGRICULTURAL SEARCH
    # ==========================================
    agricultural_sources = []
    # Trigger search automatically if requested or if disease is confirmed & confidence is fair
    include_search = request.form.get("include_search", "true").lower() == "true"
    if include_search and not disease_info.get("is_healthy", False) and not is_uncertain:
        try:
            agricultural_sources = search_agriculture(
                disease_name=condition_display,
                crop_name=crop_display
            ) or []
        except Exception as exc:
            app.logger.warning("SerpApi search during diagnose failed: %s", exc)
            agricultural_sources = []

    # Clean up PyTorch GPU memory if on CUDA
    if torch.cuda.is_available() and DEVICE.startswith("cuda"):
        torch.cuda.empty_cache()

    return jsonify({
        "success": True,
        "image_warning": " ".join(image_warnings) if image_warnings else None,
        "prediction": {
            "class_name": top1_class_name,
            "crop": primary_crop,
            "crop_display": crop_display,
            "condition": primary_condition,
            "condition_display": condition_display,
            "confidence": confidence_pct,
            "confidence_level": level,
        },
        "top_predictions": top_predictions,
        "uncertainty": {
            "is_uncertain": is_uncertain,
            "rejection_reason": rejection_reason,
            "rejection_message": rejection_message,
        },
        "information": disease_info,
        "disclaimer": PRELIMINARY_DISCLAIMER,
        "agricultural_sources": agricultural_sources,
    })


