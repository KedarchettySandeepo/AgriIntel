# ==========================================
# HELPER FUNCTIONS
# ==========================================
def get_crop_name(class_name: str) -> str:
    if "___" in class_name:
        return class_name.split("___", 1)[0]
    return class_name


def get_condition_name(class_name: str) -> str:
    if "___" in class_name:
        return class_name.split("___", 1)[1]
    return class_name


def clean_display_name(text: str) -> str:
    clean = str(text or "").replace("_", " ").replace("  ", " ").strip()
    if clean.lower() == "corn (maize)":
        return "Corn (Maize)"
    if clean.lower() == "pepper, bell":
        return "Bell Pepper"
    if clean.lower() == "cherry (including sour)":
        return "Cherry"
    return clean


def confidence_level(confidence: float) -> str:
    if confidence >= 0.80:
        return "high"
    if confidence >= 0.60:
        return "medium"
    return "low"


